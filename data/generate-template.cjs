function buildSheetWithHeaders(headers, rows) {
    const aoa = [headers.slice()];
    rows.forEach(row => {
        aoa.push(headers.map(h => (row[h] === undefined ? '' : row[h])));
    });
    const sheet = XLSX.utils.aoa_to_sheet(aoa);
    sheet['!cols'] = headers.map(h => ({ wch: Math.max(12, Math.min(40, String(h).length * 2 + 8)) }));
    return sheet;
}

const wb = XLSX.utils.book_new();
XLSX.utils.book_append_sheet(wb, buildSheetWithHeaders(articlesHeader, articlesData), 'articles');
XLSX.utils.book_append_sheet(wb, buildSheetWithHeaders(questionsHeader, questionsData), 'questions');

const outputPath = path.resolve(__dirname, 'articles.xlsx');
const buf = XLSX.write(wb, { bookType: 'xlsx', type: 'buffer' });
fs.writeFileSync(outputPath, buf);
console.log('已生成 Excel 模板：' + outputPath);
